-- V4: auditoría e índices. Los objetos ya presentes en un esquema dev legado se conservan.
declare
 n number;
 procedure columna(tabla varchar2, nombre varchar2) is n number;
 begin
  select count(*) into n from user_tab_columns where table_name=upper(tabla) and column_name=upper(nombre);
  if n=0 then execute immediate 'alter table '||tabla||' add ('||nombre||' varchar2(50 char))'; end if;
 end;
begin
 columna('categorias','creado_por'); columna('categorias','modificado_por');
 columna('productos','creado_por'); columna('productos','modificado_por');
 columna('clientes','creado_por'); columna('clientes','modificado_por'); columna('ventas','creado_por');
 select count(*) into n from user_tables where table_name='AUDITORIA_EVENTOS';
 if n=0 then
  execute immediate 'create table auditoria_eventos (
   id number(19,0) generated by default as identity, fecha timestamp(6) not null,
   usuario varchar2(50 char) not null, accion varchar2(40 char) not null,
   entidad varchar2(40 char) not null, entidad_id number(19,0), detalle varchar2(500 char),
   request_id varchar2(36 char), constraint pk_auditoria_eventos primary key(id))';
 end if;
end;
/
declare
 procedure indice(nombre varchar2, sentencia varchar2) is n number;
 begin
  select count(*) into n from user_indexes where index_name=upper(nombre);
  if n=0 then execute immediate sentencia; end if;
 end;
begin
 indice('ix_auditoria_fecha','create index ix_auditoria_fecha on auditoria_eventos(fecha)');
 indice('ix_auditoria_usuario','create index ix_auditoria_usuario on auditoria_eventos(usuario,fecha)');
 indice('ix_productos_nombre','create index ix_productos_nombre on productos(nombre)');
end;
/
